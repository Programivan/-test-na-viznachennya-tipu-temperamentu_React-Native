/**
 * Розрахунок типу темпераменту за сумою балів (методика Айзенка з naurok.com.ua):
 * 0 - 13: Сангвінік-екстраверт
 * 14 - 27: Флегматик-інтроверт
 * 28 - 40: Холерик-екстраверт
 * 41+: Меланхолік-інтроверт
 */
export function calculateTemperamentByScore(score, totalQuestions) {
  // Нормалізуємо бал, якщо запитань менше ніж 42
  const normalizedScore =
    totalQuestions === 42 ? score : (score / totalQuestions) * 42;

  if (normalizedScore <= 13) {
    return TEMPERAMENTS.sanguine;
  } else if (normalizedScore <= 27) {
    return TEMPERAMENTS.phlegmatic;
  } else if (normalizedScore <= 40) {
    return TEMPERAMENTS.choleric;
  } else {
    return TEMPERAMENTS.melancholic;
  }
}
